import assert from 'node:assert/strict';
import {checkScript} from './lib/verify.mjs';
import {wordTimings} from './lib/voice.mjs';
import {templateScript} from './lib/llm.mjs';
const T = ['Hamilton se une a Ferrari en 2025', 'Ferrari confirma a Hamilton para 2025'];
assert.ok(checkScript('Lewis Hamilton ficha por Ferrari en 2025, y lo confirman dos medios. Todo el equipo lo celebra con la afición.'.replace('Lewis ',''), T).ok);
assert.ok(!checkScript('Hamilton ficha por Ferrari por 40 millones y Verstappen lo comenta sin parar en redes hoy.', T).ok, 'cifra inventada');
assert.ok(checkScript('Hamilton ficha por Ferrari por 40 millones y Verstappen lo comenta sin parar en redes hoy.', T).problems.some((p) => p.includes('Verstappen')));
assert.ok(!checkScript('Hola.', T).ok);
const w = wordTimings('uno dos tres cuatro.', 4);
assert.equal(w.length, 4); assert.ok(w[3].end <= 4.001 && w[0].start >= 0);
assert.ok(templateScript({headline: 'Hamilton ficha por Ferrari.', level: 'MEDIA', sources: [{name: 'AS'}, {name: 'Marca'}]}).includes('2 medios'));
console.log('✓ agentes: verificador, tiempos y plantilla OK');
import {routeCluster, marketKind, propsFor} from '../lib/classify.mjs';
import {buildWeek} from '../fetch-calendar.mjs';
assert.equal(routeCluster({level: 'RADAR', headline: 'x'}).composition, 'Rumor');
assert.equal(routeCluster({level: 'ALTA', headline: 'Hamilton renueva con Ferrari hasta 2027'}).composition, 'Mercado');
assert.equal(routeCluster({level: 'ALTA', headline: 'Sanciones tras el GP de Brasil'}).composition, 'NoticiaVerificada');
assert.equal(marketKind('Hamilton renueva con Ferrari'), 'RENOVACIÓN');
const rp = propsFor({composition: 'Rumor'}, {headline: 'h', latest: '2026-11-08', sources: [], alsoSay: [{name: 'Nachez', domain: 'x.com', tier: 'creador'}]}, () => '08 NOV');
assert.equal(rp.sources.length, 1);
const wk = buildWeek({season: '2026', round: '21', raceName: 'Brazilian Grand Prix', Circuit: {circuitName: 'Interlagos', Location: {country: 'Brazil'}}, date: '2026-11-08', time: '17:00:00Z', FirstPractice: {date: '2026-11-06', time: '14:30:00Z'}, Qualifying: {date: '2026-11-07', time: '18:00:00Z'}});
assert.equal(wk.props.gp, 'GP de Brasil'); assert.equal(wk.props.sessions.at(-1).time, '18:00'); assert.equal(wk.props.sessions.at(-1).name, 'Carrera');
console.log('✓ clasificación de series y calendario OK');

assert.ok(/no est[aá] confirmado/.test(templateScript({level: 'RADAR', headline: 'Algo', sources: [{name: 'AS'}], alsoSay: [{name: 'Nachez'}]})));
console.log('✓ guion de rumor dice NO confirmado');
import {topicsOf} from '../lib/classify.mjs';
const tc = topicsOf({headline: 'Alonso renueva con Aston Martin hasta 2028', sources: [{title: 'Alonso signs extension'}], alsoSay: []});
assert.ok(tc.includes('alonso') && tc.includes('aston') && !tc.includes('ferrari'));
console.log('✓ temas (pilotos/equipos) detectados');
import {isSpanish} from './lib/verify.mjs';
assert.ok(isSpanish('Norris gana en Brasil y Mercedes se acerca al título de pilotos tras una carrera loca'));
assert.ok(!isSpanish('How Verstappen outperformed Red Bull simulations in the race at Brazil'));
console.log('✓ detector de idioma (español / inglés)');
